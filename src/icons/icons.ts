export const getVariantsWithCommonClass = (
  icons: IconMapTypes[],
  commonClass: string
) => {
  return icons.reduce((acc, icon) => {
    acc[icon] = `${commonClass}`;
    return acc;
  }, {} as { [key in IconMapTypes]: string });
};

